import type { ModuleInfo, Queue } from "../../types";

function mod(
  name: string,
  title: string,
  queue: Queue,
  inputs: string[],
  description: string,
  source_url: string | null,
  requires_env: string[] = [],
  available = true,
): ModuleInfo {
  return { name, title, description, inputs, queue, requires_env, available, source_url };
}

